CREATE TABLE clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    api_key_hash text NOT NULL UNIQUE CHECK (char_length(api_key_hash) = 64),
    from_email text NOT NULL CHECK (char_length(from_email) <= 320),
    from_name text,
    rate_limit_per_sec integer NOT NULL CHECK (rate_limit_per_sec > 0),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE batches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES clients (id),
    idempotency_key text CHECK (idempotency_key IS NULL OR char_length(idempotency_key) <= 128),
    subject text NOT NULL CHECK (char_length(subject) BETWEEN 1 AND 255),
    html text NOT NULL CHECK (octet_length(html) <= 262144),
    text text NOT NULL,
    -- effective sender chosen at ingest: request.from or clients.from_email
    from_email text NOT NULL CHECK (char_length(from_email) <= 320),
    created_at timestamptz NOT NULL DEFAULT now(),
    html_purged_at timestamptz,
    UNIQUE (client_id, idempotency_key)
);

CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES batches (id) ON DELETE CASCADE,
    client_id bigint NOT NULL REFERENCES clients (id),
    recipient text NOT NULL CHECK (recipient <> ''),
    status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sending', 'sent', 'failed')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    sent_at timestamptz
);

CREATE INDEX messages_status_idx ON messages (status);
CREATE INDEX messages_batch_id_idx ON messages (batch_id);
CREATE INDEX messages_created_at_idx ON messages (created_at);

CREATE TABLE outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    published_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX outbox_published_at_idx ON outbox (published_at);
